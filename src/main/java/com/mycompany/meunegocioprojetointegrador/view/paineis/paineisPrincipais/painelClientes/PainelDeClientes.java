    private void jBEditarClienteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBEditarClienteActionPerformed
        var items=jList1.getSelectedIndices();
        if(items.length>1){avisoMuitosItemsSelecionados("editar");return;}
        if(items.length<1){avisoNenhumItemSelecionado("Edicao");return;}
        var itemselecionado=((ModeloListaCOntatos)jList1.getModel()).getItemSelecionado(items[0]);
        navegacao.navegar(new Rotas.AdicionarCliente(itemselecionado));
    }//GEN-LAST:event_jBEditarClienteActionPerformed

    private void jBPesquisarClientesActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBPesquisarClientesActionPerformed
        var clicados=jList1.getSelectedIndices();
        if(clicados.length>1){avisoMuitosItemsSelecionados("visualizar ");return;}
        if(clicados.length<1){avisoNenhumItemSelecionado("visualizar");return;}
        var modelo =jList1.getSelectedValue();
        navegacao.navegar(new Rotas.VisualizarCliente(modelo));
    }//GEN-LAST:event_jBPesquisarClientesActionPerformed

    private void jBPesquisarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBPesquisarActionPerformed
        var objetoSelecionado =(EnunPesquisaClientes) jCBTipoDePesquisa.getSelectedItem();
        if(objetoSelecionado==null) {
           JOptionPane.showMessageDialog(this,"Nenuma Opcao De Pesquisa Selecionada");
           return;
        }
        controle.pesquisar(jtPesquisa.getText(),objetoSelecionado );
    }//GEN-LAST:event_jBPesquisarActionPerformed

