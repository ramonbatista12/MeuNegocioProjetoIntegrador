    private void jBExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBExcluirActionPerformed
       var item = jList1.getSelectedIndices();
       if(item.length>1){
       JOptionPane.showMessageDialog(jPanel3,"E nessesario selecionar apenas um item para exlucsao");
       return;
       }
       if(item.length<=0){
           JOptionPane.showMessageDialog(jPanel3,"Nenhum item foi selecionado");
           return;
       }
       var resposta =JOptionPane.showConfirmDialog(jPanel3,"Excluir um cliente tambem excluira todo o seu historico ","Obss :",JOptionPane.OK_CANCEL_OPTION);
       if(resposta!=JOptionPane.OK_OPTION){return;}
        
       controle.apagarCliente(((ModeloListaCOntatos)jList1.getModel()).getItemSelecionado(item[0]));
       
    }//GEN-LAST:event_jBExcluirActionPerformed

